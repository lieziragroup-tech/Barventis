    LEFT JOIN public.material_location_costs c
      ON c.tenant_id = m.tenant_id AND c.material_id = m.id AND c.location = NEW.location
    WHERE i.opname_id = NEW.id AND i.material_id = m.id AND m.tenant_id = NEW.tenant_id;
  END IF;
  RETURN NEW;
END;
